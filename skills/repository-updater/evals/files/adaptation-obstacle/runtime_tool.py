import json
import sys
from pathlib import Path


def main():
    root = Path(__file__).parent
    config = json.loads((root / "runtime.json").read_text())
    flags = ",".join(config["compatibilityFlags"])
    expected = f"# Generated by runtime {config['version']} {flags}\nNODE_COMPAT = True\n"
    declarations = root / "runtime_types.py"

    if sys.argv[1:] == ["generate"]:
        declarations.write_text(expected)
        print("Declarations generated.")
    elif sys.argv[1:] == ["check"]:
        if declarations.read_text() != expected:
            raise SystemExit("Generated declarations are out of date.")
        print("Configuration and generated declarations match.")
    else:
        raise SystemExit("Usage: runtime_tool.py generate|check")


if __name__ == "__main__":
    main()
